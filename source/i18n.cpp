void i18nSetLang(const std::string& lang) { g_english = (lang == "en"); }

const char* tr(const char* key) {
    for (const Str& s : kStrings)
        if (strcmp(s.key, key) == 0) return g_english ? s.en : s.es;
    return key;
}
